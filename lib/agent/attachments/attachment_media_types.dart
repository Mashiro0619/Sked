String attachmentMediaType(String name, [String? declared]) {
  final normalizedName = name.toLowerCase();
  final known = switch (normalizedName) {
    'makefile' || 'gnumakefile' => 'text/x-makefile',
    'cmakelists.txt' => 'text/x-cmake',
    _ => _extensionMediaTypes[normalizedName.split('.').last],
  };
  if (known != null) return known;
  final normalized = declared?.split(';').first.trim().toLowerCase();
  return normalized != null &&
          RegExp(r'^[a-z0-9!#$&^_.+-]+/[a-z0-9!#$&^_.+-]+$')
              .hasMatch(normalized)
      ? normalized
      : 'application/octet-stream';
}
