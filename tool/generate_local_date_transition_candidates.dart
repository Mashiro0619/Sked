import 'dart:io';
import 'dart:isolate';

import 'package:timezone/data/latest_all.dart' as data;
import 'package:timezone/timezone.dart' as tz;

/// Regenerate after changing the timezone dependency or its bundled IANA data.
Future<void> main() async {
  // Only this standalone tool process initializes the timezone package. The
  // application model uses the generated instants and native DateTime rules.
  data.initializeTimeZones();
  final candidates = <int>{};
  int? unlocatedHistoryEnd;
  for (final location in tz.timeZoneDatabase.locations.values) {
    for (final instant in location.transitionAt) {
      final before = location.timeZone(instant - 1).offset;
      final after = location.timeZone(instant).offset;
      if (after - before < const Duration(hours: 12)) continue;
      if (instant == tz.minTime) {
        // The serialized initial zone may hide an older date-line shift. Keep
        // native calendar probing up to its next explicit transition.
        final next = location.transitionAt.firstWhere(
          (value) => value > tz.minTime,
        );
        if (unlocatedHistoryEnd == null || next > unlocatedHistoryEnd) {
          unlocatedHistoryEnd = next;
        }
      } else {
        candidates.add(instant);
      }
    }
  }
  final ordered = candidates.toList()..sort();
  final dataUri = await Isolate.resolvePackageUri(
    Uri.parse('package:timezone/data/latest_all.dart'),
  );
  final source = await File.fromUri(dataUri!).readAsString();
  final dataVersion = RegExp(r'Timezone data version: (\S+)')
      .firstMatch(source)!
      .group(1);
  final root = File.fromUri(Platform.script).parent.parent;
  final output = File(
    '${root.path}/lib/models/local_date_transition_candidates.dart',
  );
  final lines = <String>[
    '// Generated by tool/generate_local_date_transition_candidates.dart.',
    '// Source: timezone latest_all IANA $dataVersion. Do not edit by hand.',
    '// Candidate instants are checked against the native local calendar;',
    '// they never replace its timezone rules or initialize the global TZ state.',
    '',
    'const localDateTransitionCandidateMilliseconds = <int>[',
    for (final instant in ordered)
      '  $instant, // ${DateTime.fromMillisecondsSinceEpoch(instant, isUtc: true).toIso8601String()}',
    '];',
    '',
    'const localDateTransitionUnlocatedHistoryEndMilliseconds = ${unlocatedHistoryEnd ?? 0};',
    '',
  ];
  await output.writeAsString(lines.join('\n'));
  stdout.writeln(
    'Generated ${ordered.length} transition candidates: ${output.path}',
  );
}
