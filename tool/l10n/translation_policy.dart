Set<String> allowedFallbacksForLocale(String locale) {
  final language = locale.replaceAll('-', '_').split('_').first;
  if (language == 'en' || language == 'zh') return const {};
  return {...commonEnglishFallbacks, ...?localeEnglishFallbacks[locale]};
}

